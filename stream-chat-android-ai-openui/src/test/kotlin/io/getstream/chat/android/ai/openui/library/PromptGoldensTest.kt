/**
 * `fixtures/prompt-goldens.json` holds system prompts generated by upstream's
 * `generateSystemPrompt` for option combinations of the chat and standard libraries and the
 * OpenUI 1.0 specification's library.
 */
internal class PromptGoldensTest {

    data class Golden(val name: String, val library: String, val options: OpenUIValue, val prompt: String)

    private val goldens: List<Golden> = Fixtures.json("prompt-goldens.json").arrayValue.orEmpty().map {
        Golden(
            it["name"].stringValue!!,
            it["library"].stringValue!!,
            it["options"] ?: OpenUIValue.Obj(OpenUIObject.Empty),
            it["prompt"].stringValue!!,
        )
    }

    @Test
    fun `fixtures are loaded`() {
        assertEquals(14, goldens.size)
        assertEquals(setOf("chat", "standard", "spec"), goldens.map { it.library }.toSet())
    }

    /** The generator alone, fed the upstream spec. */
    @TestFactory
    fun `generator matches upstream`(): List<DynamicTest> = goldens.map { golden ->
        DynamicTest.dynamicTest(golden.name) {
            val spec = Fixtures.json(specFile(golden.library))
            val prompt = PromptGenerator.generate(PromptSpec.fromLibrarySpec(spec, promptOptions(golden.options)))
            assertNull(firstLineDifference(prompt, golden.prompt), golden.name)
        }
    }

    /** End to end: the Kotlin library definitions and the generator. */
    @TestFactory
    fun `kotlin library prompt matches upstream`(): List<DynamicTest> = goldens.map { golden ->
        DynamicTest.dynamicTest(golden.name) {
            val prompt = library(golden.library).systemPrompt(promptOptions(golden.options))
            assertNull(firstLineDifference(prompt, golden.prompt), golden.name)
        }
    }

    @Test
    fun `default prompt options match upstream`() {
        assertEquals(goldens.single { it.name == "chat-default" }.prompt, LibraryDefinition.chat.systemPrompt())
        assertEquals(goldens.single { it.name == "standard-default" }.prompt, LibraryDefinition.standard.systemPrompt())
    }

    companion object {
        fun specFile(library: String) = when (library) {
            "chat" -> "upstream-chat-library.spec.json"
            "spec" -> "spec-library.json"
            else -> "upstream-playground-library.spec.json"
        }

        fun library(name: String) = when (name) {
            "chat" -> LibraryDefinition.chat
            "spec" -> SpecLibrary.library
            else -> LibraryDefinition.standard
        }

        fun promptOptions(json: OpenUIValue): PromptOptions {
            fun strings(key: String) = json[key].arrayValue.orEmpty().mapNotNull { it.stringValue }
            val empty = OpenUIValue.Obj(OpenUIObject.Empty)
            return PromptOptions(
                preamble = json["preamble"].stringValue,
                additionalRules = strings("additionalRules"),
                examples = strings("examples"),
                toolExamples = strings("toolExamples"),
                tools = json["tools"].arrayValue.orEmpty().map { tool ->
                    tool.stringValue?.let { ToolDescriptor.Name(it) } ?: ToolDescriptor.Spec(
                        ToolSpec(
                            tool["name"].stringValue.orEmpty(),
                            tool["description"].stringValue,
                            tool["inputSchema"] ?: empty,
                            tool["outputSchema"] ?: empty,
                        ),
                    )
                },
                editMode = json["editMode"].boolValue ?: false,
                inlineMode = json["inlineMode"].boolValue ?: false,
                toolCalls = json["toolCalls"].boolValue,
                bindings = json["bindings"].boolValue,
                builtinFunctions = json["builtinFunctions"].boolValue,
            )
        }

        fun firstLineDifference(actual: String, expected: String): String? {
            if (actual == expected) return null
            val a = actual.split("\n")
            val e = expected.split("\n")
            for (index in 0 until maxOf(a.size, e.size)) {
                val left = a.getOrElse(index) { "<missing>" }
                val right = e.getOrElse(index) { "<missing>" }
                if (left != right) return "line ${index + 1}:\n  actual:   $left\n  expected: $right"
            }
            return "lengths differ"
        }
    }
}
